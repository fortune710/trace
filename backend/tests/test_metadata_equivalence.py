def test_table_columns_and_metadata_names_are_stable() -> None:
    assert set(Base.metadata.tables) == set(EXPECTED_COLUMNS)
    for table_name, columns in EXPECTED_COLUMNS.items():
        table = Base.metadata.tables[table_name]
        assert {column.name for column in table.c} == columns
        assert table.fullname == table_name


def test_primary_keys_foreign_keys_and_named_constraints_are_registered() -> None:
    projects = Base.metadata.tables["public.projects"]
    assert set(projects.primary_key.columns.keys()) == {"id"}
    assert {constraint.name for constraint in projects.constraints} >= {
        "projects_owner_id_id_key",
        "projects_source_reference_check",
        "projects_issue_tracking_details_shape_check",
    }
    assert {
        (foreign_key.parent.name, foreign_key.target_fullname)
        for foreign_key in projects.foreign_keys
    } >= {
        ("owner_id", "public.users.id"),
    }

    findings = Base.metadata.tables["public.findings"]
    assert {foreign_key.target_fullname for foreign_key in findings.foreign_keys} >= {
        "public.users.id",
        "public.review_agents.owner_id",
        "public.review_agents.review_id",
        "public.review_agents.agent_id",
    }

    dispatch_jobs = Base.metadata.tables["private.review_dispatch_jobs"]
    assert {
        foreign_key.target_fullname for foreign_key in dispatch_jobs.foreign_keys
    } >= {
        "public.users.id",
        "public.review_agents.owner_id",
        "public.review_agents.review_id",
        "public.review_agents.id",
    }

    notifications = Base.metadata.tables["public.notifications"]
    assert {
        foreign_key.target_fullname for foreign_key in notifications.foreign_keys
    } == {"public.users.id"}
    assert {constraint.name for constraint in notifications.constraints} >= {
        "notifications_owner_dedupe_key",
        "notifications_title_length",
        "notifications_body_length",
        "notifications_action_path_relative",
    }


